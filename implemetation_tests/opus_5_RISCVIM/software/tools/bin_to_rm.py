#!/usr/bin/env python3
"""bin -> .rm converter.

REQ: FR-13 (design) / pipeline:FR-20, pipeline:FR-21

Reads the raw binary produced by `objcopy -O binary` and emits the `.rm`
format documented in specs/plan.md ("Formato do .rm"): text, one 32-bit
little-endian word per line in hexadecimal, lowest address first, `#`
comment lines carrying provenance.

The `.rm` is always derived by tool from the ELF -- never hand written.
"""
from __future__ import annotations

import argparse
import pathlib
import sys


def bin_to_words(data: bytes) -> list[int]:
    if len(data) % 4 != 0:
        data = data + b"\x00" * (4 - len(data) % 4)
    return [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="binary -> .rm (SpecHDL ROM image)")
    parser.add_argument("binary", type=pathlib.Path)
    parser.add_argument("rm", type=pathlib.Path)
    parser.add_argument("--origin", default="0x00000000")
    parser.add_argument("--source", default=None, help="ELF path recorded in the header")
    args = parser.parse_args(argv)

    words = bin_to_words(args.binary.read_bytes())
    origin = int(args.origin, 0)
    source = args.source or str(args.binary)

    lines = [
        "# program.rm -- generated by software/tools/bin_to_rm.py (do not edit by hand)",
        f"# origin=0x{origin:08x}  words={len(words)}  source={source}",
    ]
    lines += [f"{w:08x}" for w in words]
    args.rm.write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"{args.rm}: {len(words)} words from {source}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
