#!/usr/bin/env python3
""".rm -> rom_image_pkg.vhd generator.

REQ: FR-13 (design) / pipeline:FR-21

Turns the `.rm` ROM image into a generated VHDL package holding the constant
instruction array, which the program Makefile compiles together with the CPU
sources. Chosen over reading the file with std.textio at elaboration time
because a ROM with file I/O does not survive Yosys synthesis, and phase 5 has
to synthesise the very design that was verified (specs/plan.md).

The `.rm` remains the real artifact; this package is derived and disposable.
"""
from __future__ import annotations

import argparse
import pathlib
import sys

HEADER = """-- =============================================================================
-- rom_image_pkg.vhd -- GENERATED FILE, DO NOT EDIT BY HAND
-- REQ: FR-13 (pipeline:FR-21)
--
-- Generated by software/tools/rm_to_rom_pkg.py from:
--   {rm}
-- Words in image: {used} of {size} (rest padded with zeros)
-- =============================================================================

library ieee;
use ieee.std_logic_1164.all;
use work.cpu_pkg.all;

package rom_image_pkg is
    constant ROM_IMAGE : rom_image_t := (
"""

FOOTER = """        others => x"00000000"
    );
end package rom_image_pkg;
"""


def parse_rm(path: pathlib.Path) -> list[int]:
    words: list[int] = []
    for line in path.read_text(encoding="ascii").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        words.append(int(line, 16))
    return words


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=".rm -> rom_image_pkg.vhd")
    parser.add_argument("rm", type=pathlib.Path)
    parser.add_argument("vhdl", type=pathlib.Path)
    parser.add_argument("--size", type=int, default=1024, help="ROM_SIZE_WORDS of cpu_pkg")
    args = parser.parse_args(argv)

    words = parse_rm(args.rm)
    if len(words) > args.size:
        print(
            f"error: image has {len(words)} words, ROM holds {args.size} "
            f"(FR-06). Shrink the program or widen the ROM in cpu_pkg.vhd.",
            file=sys.stderr,
        )
        return 1

    body = "".join(
        f'        {i} => x"{w:08x}",\n' for i, w in enumerate(words)
    )
    text = HEADER.format(rm=args.rm.as_posix(), used=len(words), size=args.size) + body + FOOTER
    args.vhdl.write_text(text, encoding="ascii")
    print(f"{args.vhdl}: {len(words)}/{args.size} words")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
